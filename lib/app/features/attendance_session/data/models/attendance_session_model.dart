import '../../domain/entities/attendance_event_entity.dart';
import '../../domain/entities/attendance_session_entity.dart';
import '../../domain/entities/attendance_type.dart';
import '../../domain/entities/location_entity.dart';
import '../../domain/entities/shift_entity.dart';

/// [AttendanceSessionEntity] from an `attendance_records` row with its
/// embedded `attendance_events`.
///
/// For saved events, `selfiePath` is the Storage object path in the
/// `attendance-evidence` bucket, not a local file.
class AttendanceSessionModel extends AttendanceSessionEntity {
  const AttendanceSessionModel({
    required super.id,
    required super.checkIn,
    required super.shift,
    super.checkOut,
    super.scheduledEnd,
    super.closeDeadline,
    super.autoClosedAt,
    super.effectiveCheckIn,
    super.effectiveCheckOut,
    super.hasCorrection,
    super.lateMinutes,
    super.workDate,
    super.timezone,
  });

  /// Throws a [FormatException] when a required column is missing.
  factory AttendanceSessionModel.fromJson(
    Map<String, dynamic> json, {
    required ShiftEntity shift,
  }) {
    final events = (json['attendance_events'] as List? ?? const [])
        .cast<Map<String, dynamic>>();
    Map<String, dynamic>? eventOf(String type) =>
        events.where((e) => e['event_type'] == type).firstOrNull;

    final checkInTime = _time(json['actual_checkin']);
    if (checkInTime == null) {
      throw const FormatException('Attendance has no actual_checkin');
    }
    final checkOutTime = _time(json['actual_checkout']);
    final autoClosed = json['auto_closed'] == true;

    return AttendanceSessionModel(
      id: json['id'] as String,
      shift: shift,
      checkIn: _event(AttendanceType.checkIn, checkInTime, eventOf('check_in')),
      checkOut: checkOutTime == null
          ? null
          : _event(AttendanceType.checkOut, checkOutTime, eventOf('check_out')),
      scheduledEnd: _time(json['scheduled_end']),
      // Generated by the database from auto_close_policy (midnight after
      // the work date by default, or the shift end).
      closeDeadline: _time(json['auto_close_deadline']),
      autoClosedAt: autoClosed
          ? _time(json['auto_closed_at']) ?? _time(json['auto_close_deadline'])
          : null,
      effectiveCheckIn: _time(json['effective_checkin']),
      effectiveCheckOut: _time(json['effective_checkout']),
      hasCorrection: json['has_correction'] == true,
      lateMinutes: (json['late_minutes'] as num?)?.toInt() ?? 0,
      workDate: _date(json['work_date']),
      timezone: json['timezone'] as String?,
    );
  }

  /// Postgres `date` as text, e.g. "2026-10-25", as a date-only value.
  static DateTime? _date(Object? value) {
    if (value is! String) return null;
    final date = DateTime.parse(value);
    return DateTime(date.year, date.month, date.day);
  }

  /// The record's own time is the authority. The event adds the evidence;
  /// it can be missing in malformed history.
  static AttendanceEventEntity _event(
    AttendanceType type,
    DateTime time,
    Map<String, dynamic>? event,
  ) {
    final latitude = event?['latitude'] as num?;
    final longitude = event?['longitude'] as num?;
    final accuracy = event?['accuracy_m'] as num?;
    return AttendanceEventEntity(
      type: type,
      time: time,
      location: latitude == null || longitude == null || accuracy == null
          ? null
          : LocationEntity(
              latitude: latitude.toDouble(),
              longitude: longitude.toDouble(),
              accuracyMeters: accuracy.toDouble(),
              capturedAt: _time(event?['occurred_at']) ?? time,
            ),
      selfiePath: event?['selfie_path'] as String?,
    );
  }

  static DateTime? _time(Object? value) =>
      value is String ? DateTime.parse(value) : null;
}
